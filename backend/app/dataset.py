"""Loader for the shared synthetic city dataset (``data/city``).

The dataset is generated by ``data/generate_city.py`` (see its module docstring).
It is the common world state consumed by later milestones — baseline twin,
synthetic population, simulation, and the 3D map. This module is a thin, cached
reader; it does not compute simulation effects.

Provenance: every record originates from the ``Synthetic`` dataset (see
``manifest.json``). Nothing here is an LLM-generated numeric effect (SPEC §34).
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path
from typing import Any

# repo_root/backend/app/dataset.py -> repo_root/data/city
_DATA_DIR = Path(__file__).resolve().parents[2] / "data" / "city"


class DatasetError(RuntimeError):
    """Raised when the shared dataset is missing or malformed."""


def data_dir() -> Path:
    """Directory holding the generated city dataset."""
    return _DATA_DIR


def _read_json(name: str) -> Any:
    path = _DATA_DIR / name
    if not path.exists():
        raise DatasetError(
            f"Missing dataset file: {path}. Run `python data/generate_city.py`."
        )
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:  # pragma: no cover - defensive
        raise DatasetError(f"Malformed dataset file {path}: {exc}") from exc


@lru_cache(maxsize=1)
def load_manifest() -> dict:
    return _read_json("manifest.json")


@lru_cache(maxsize=1)
def load_zones() -> dict:
    """Zone GeoJSON FeatureCollection."""
    return _read_json("zones.geojson")


@lru_cache(maxsize=1)
def load_roads() -> dict:
    """Road-network GeoJSON FeatureCollection."""
    return _read_json("roads.geojson")


@lru_cache(maxsize=1)
def load_od_pairs() -> dict:
    """Origin→destination trip table."""
    return _read_json("od_pairs.json")


@lru_cache(maxsize=1)
def load_cbd_polygon() -> dict:
    """The central-district cordon polygon (priced/pedestrianised area)."""
    return _read_json("cbd_polygon.geojson")


def zone_index() -> dict[str, dict]:
    """Map zone_id -> zone properties for quick lookups."""
    return {
        f["properties"]["zone_id"]: f["properties"]
        for f in load_zones()["features"]
    }


def cbd_zone_ids() -> set[str]:
    """Zone ids inside the central district."""
    return {
        f["properties"]["zone_id"]
        for f in load_zones()["features"]
        if f["properties"].get("is_cbd")
    }


def clear_cache() -> None:
    """Drop cached reads (used by tests / after regeneration)."""
    for fn in (
        load_manifest,
        load_zones,
        load_roads,
        load_od_pairs,
        load_cbd_polygon,
    ):
        fn.cache_clear()
